#!/bin/bash
# Builds cloud-init.sh, the file pasted into Oracle Cloud. The full
# setup-node.sh (with the chain patches) is larger than Oracle's 32,000-byte
# metadata limit, so cloud-init.sh downloads it from the public repo
# github.com/pospos191-alt/zetaphy-chain (file v/<sha256>.sh, never changed
# once published) and runs it only if its SHA-256 matches the one written here.
#   ./pack-cloud-init.sh          rewrite cloud-init.sh and public/v/<sha256>.sh
#   ./pack-cloud-init.sh --check  fail if cloud-init.sh is out of date (CI)
set -euo pipefail
cd "$(dirname "$0")"
PUBLIC_REPO=pospos191-alt/zetaphy-chain
sha=$(sha256sum setup-node.sh | cut -d' ' -f1)
url="https://raw.githubusercontent.com/$PUBLIC_REPO/main/v/$sha.sh"
out=$(cat <<SH
#!/bin/bash
# ZETAPHY Chain node setup for Oracle Cloud. Paste this whole file into:
#   Create instance -> Show advanced options -> Management -> Paste cloud-init script
# It downloads setup-node.sh (the same file as zetaphy-chain/setup-node.sh
# in the project, published at github.com/$PUBLIC_REPO) and runs it only if
# its SHA-256 fingerprint matches the one below. Generated by pack-cloud-init.sh.
#
# OPTIONAL: put your MetaMask address between the quotes to receive
# 1,000,000 test ZETAPHY at genesis (public address only, never a private key).
OWNER_EVM_ADDRESS=""

set -euo pipefail
f=/root/zetaphy-setup-node.sh
for i in 1 2 3 4 5 6; do curl -fsSL "$url" -o "\$f" && break; sleep 20; done
echo "$sha  \$f" | sha256sum -c --quiet -
chmod 700 "\$f"
OWNER_EVM_ADDRESS="\$OWNER_EVM_ADDRESS" exec bash "\$f"
SH
)
if [ "${1:-}" = "--check" ]; then
  printf '%s\n' "$out" | cmp -s - cloud-init.sh || { echo "cloud-init.sh is out of date: run zetaphy-chain/pack-cloud-init.sh"; exit 1; }
  echo "cloud-init.sh matches setup-node.sh ($sha)"
else
  printf '%s\n' "$out" > cloud-init.sh
  rm -rf public && mkdir -p public/v && cp setup-node.sh "public/v/$sha.sh" && cp setup-node.sh public/setup-node.sh
  cat > public/README.md <<MD
# ZETAPHY chain node setup

Published copy of the node setup script for the ZETAPHY testnet (Cosmos EVM
with post-quantum ML-DSA-44 accounts and vote signatures).

- \`setup-node.sh\`: the latest version
- \`v/<sha256>.sh\`: every published version, named by its SHA-256 and never
  changed; the Oracle Cloud \`cloud-init.sh\` downloads one of these and runs
  it only if the fingerprint matches

Testnet only. No keys or secrets are in this repository.
MD
  echo "wrote cloud-init.sh ($(wc -c < cloud-init.sh) bytes); publish public/ to github.com/$PUBLIC_REPO"
fi
