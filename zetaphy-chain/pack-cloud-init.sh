#!/bin/bash
# Builds cloud-init.sh: setup-node.sh without its comment-only lines (in the
# patches, only new Go files lose theirs), compressed (xz) and
# text-encoded (base85) so it fits Oracle Cloud's limit. Oracle base64-encodes what is
# pasted and allows 32,000 bytes of instance metadata in all (SSH key
# included), so the pasted file must stay under ~23,000 bytes.
#   ./pack-cloud-init.sh          rewrite cloud-init.sh
#   ./pack-cloud-init.sh --check  fail if cloud-init.sh is out of date (CI)
set -euo pipefail
cd "$(dirname "$0")"
LIMIT=23000
out=$(python3 - <<'PY'
import base64, hashlib, lzma, re, textwrap
full = open('setup-node.sh').read()
cut = full.index('# ---- ZETAPHY patches')
lines = full[:cut].split('\n')
code = [lines[0]] + [l for l in lines[1:] if not l.lstrip().startswith('#')]
# New Go files in the patches also lose their comment-only and blank lines (each is
# one hunk, so only its line count changes); changes to upstream files stay exact.
def slim(patch):
    out = []
    for d in re.split(r'(?=^diff --git )', patch, flags=re.M):
        m = re.search(r'^new file mode .*\n(?:.*\n){3}@@ -0,0 \+1,(\d+) @@\n', d, re.M)
        if m and d.split('\n', 1)[0].endswith('.go'):
            body = [l for l in d[m.end():].split('\n') if not re.match(r'\+\s*(//(?!go:)|$)', l)]
            n = sum(1 for l in body if l.startswith('+'))
            d = d[:m.start(1)] + str(n) + ' @@\n' + '\n'.join(body)
        out.append(d)
    return ''.join(out)
src = ('\n'.join(code) + slim(full[cut:])).encode()
packed = lzma.compress(src, format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64,
                       filters=[{'id': lzma.FILTER_LZMA2, 'preset': 9 | lzma.PRESET_EXTREME}])
body = '\n'.join(textwrap.wrap(base64.b85encode(packed).decode(), 500))
sha = hashlib.sha256(src).hexdigest()
print(f'''#!/bin/bash
# ZETAPHY Chain node setup for Oracle Cloud. Paste this whole file into:
#   Create instance -> Show advanced options -> Management -> Paste cloud-init script
# It is setup-node.sh (next to this file on GitHub; read it for what runs)
# without its comment lines, compressed so it fits Oracle's size limit.
# Generated by pack-cloud-init.sh; CI checks that the two match.
#
# OPTIONAL: put your MetaMask address between the quotes to receive
# 1,000,000 test ZETAPHY at genesis (public address only, never a private key).
OWNER_EVM_ADDRESS=""

set -euo pipefail
f=/root/zetaphy-setup-node.sh
python3 -c 'import base64,lzma,sys; sys.stdout.buffer.write(lzma.decompress(base64.b85decode("".join(sys.stdin.read().split()))))' > "$f" <<'ZETAPHY_PACKED'
{body}
ZETAPHY_PACKED
echo "{sha}  $f" | sha256sum -c --quiet -
chmod 700 "$f"
OWNER_EVM_ADDRESS="$OWNER_EVM_ADDRESS" exec bash "$f"''')
PY
)
size=$(printf '%s\n' "$out" | wc -c)
[ "$size" -le "$LIMIT" ] || { echo "cloud-init.sh would be $size bytes (limit $LIMIT): too big for Oracle"; exit 1; }
if [ "${1:-}" = "--check" ]; then
  printf '%s\n' "$out" | cmp -s - cloud-init.sh || { echo "cloud-init.sh is out of date: run zetaphy-chain/pack-cloud-init.sh"; exit 1; }
  echo "cloud-init.sh up to date ($size bytes)"
else
  printf '%s\n' "$out" > cloud-init.sh
  echo "wrote cloud-init.sh ($size bytes; Oracle sees about $(( (size + 2) / 3 * 4 )) after base64)"
fi
