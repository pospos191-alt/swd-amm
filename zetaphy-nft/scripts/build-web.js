// npm run build:web: bundles src/entry.js into web/vendor/zetaphy-lib.js (committed,
// so Vercel serves it with no build step), as zetaphy-wallet/scripts/build.js does.
// Every @noble import resolves from this folder's node_modules, so the output
// depends only on package-lock.json. test/bundle.test.js rebuilds it in memory
// and fails if the committed file differs.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const OUT = ROOT + 'web/vendor/zetaphy-lib.js';

const ownDeps = {
  name: 'own-deps',
  setup(b) {
    b.onResolve({ filter: /^@noble\// }, (args) => (args.importer.startsWith(ROOT)
      ? undefined
      : b.resolve(args.path, { kind: args.kind, resolveDir: ROOT, importer: ROOT + 'src/entry.js' })));
  },
};

/** The bundle's text, built in memory. */
export async function bundle() {
  const r = await build({
    entryPoints: [ROOT + 'src/entry.js'],
    absWorkingDir: ROOT, // comments name paths relative to this folder, wherever it runs from
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    legalComments: 'inline',
    minify: false,
    plugins: [ownDeps],
    banner: { js: '// Generated by `npm run build:web` in zetaphy-nft/ from zetaphy-network/src/vaccine.js\n// and @noble/hashes (MIT). Do not edit by hand.' },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, await bundle());
  console.log('web/vendor/zetaphy-lib.js written');
}
