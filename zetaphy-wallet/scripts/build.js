// npm run build: bundles src/entry.js into vendor/pqwallet.js (committed, so
// Vercel serves it with no build step). Every @noble import resolves from
// this folder's node_modules, so the output depends only on package-lock.json.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

const ownDeps = {
  name: 'own-deps',
  setup(b) {
    b.onResolve({ filter: /^@noble\// }, (args) => (args.importer.startsWith(ROOT)
      ? undefined
      : b.resolve(args.path, { kind: args.kind, resolveDir: ROOT, importer: ROOT + 'src/entry.js' })));
  },
};

await build({
  entryPoints: [ROOT + 'src/entry.js'],
  outfile: ROOT + 'vendor/pqwallet.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  minify: false,
  plugins: [ownDeps],
  banner: { js: '// Generated by `npm run build` in zetaphy-wallet/ from zetaphy-network/src/pqtx.js and\n// @noble/post-quantum + @noble/hashes (MIT). Do not edit by hand.' },
});
console.log('vendor/pqwallet.js written');
