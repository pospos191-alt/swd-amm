/** Telegram's language_code (e.g. "th", "zh-hans", "pt-br") -> one of BOT_LANGS, English otherwise. */
export const botLang = (code) => {
  const c = String(code ?? '').toLowerCase().split('-')[0];
  return BOT_LANGS.includes(c) ? c : 'en';
};

