// Regenerates src/selectors.generated.js from src/signatures.js.
import { writeFileSync } from 'node:fs';
import { SIGNATURES } from '../src/signatures.js';
import { selectorOf } from './keccak.js';

const lines = SIGNATURES.map(([sig, cat]) =>
  `  '${selectorOf(sig)}': { sig: '${sig}', cat: '${cat}' },`);
const out = `// GENERATED by scripts/build-selectors.js from src/signatures.js. Do not edit.
export const SELECTORS = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('../src/selectors.generated.js', import.meta.url), out);
console.log(`wrote ${SIGNATURES.length} selectors`);
