// Regenerates src/tradesim.generated.js from contracts/TradeSim.sol.
//   npm run tradesim
// Dev-only: solc is a devDependency; the reader ships the compiled bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import solc from 'solc';

/** Settings are fixed so the same source always gives the same bytes. */
export function compileTradeSim() {
  const source = readFileSync(new URL('../contracts/TradeSim.sol', import.meta.url), 'utf8');
  const input = {
    language: 'Solidity',
    sources: { 'TradeSim.sol': { content: source } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      // Paris: no PUSH0 or MCOPY, so the code runs on any EVM chain's eth_call.
      evmVersion: 'paris',
      metadata: { appendCBOR: false },
      outputSelection: { '*': { TradeSim: ['evm.deployedBytecode.object', 'evm.methodIdentifiers'] } },
    },
  };
  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
  const c = out.contracts['TradeSim.sol'].TradeSim;
  const sig = Object.keys(c.evm.methodIdentifiers).find((s) => s.startsWith('run('));
  return { runtime: '0x' + c.evm.deployedBytecode.object, runSelector: c.evm.methodIdentifiers[sig], runSig: sig, solc: solc.version() };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { runtime, runSelector, runSig, solc: version } = compileTradeSim();
  const out = `// GENERATED by scripts/build-tradesim.js from contracts/TradeSim.sol. Do not edit.
// solc ${version}, optimizer 200 runs, evmVersion paris, no metadata.
export const TRADESIM_RUN = '${runSelector}'; // ${runSig}
export const TRADESIM_CODE = '${runtime}';
`;
  writeFileSync(new URL('../src/tradesim.generated.js', import.meta.url), out);
  console.log(`wrote TradeSim runtime (${(runtime.length - 2) / 2} bytes)`);
}
