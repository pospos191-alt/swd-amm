// Regenerates src/threat-signatures.generated.js: the similarity baseline and
// the seed entries of Neuro's flagged-code dataset (src/similarity.js).
//
// Source: the sample contracts in test/helpers/contracts.sol, deployed on the
// in-memory EVM (solc 0.8.26, optimizer on and off) and read back exactly as
// a runner reads a chain. Nothing is downloaded or paid for.
//
//   npm run threat-signatures
//
// test/similarity.test.js fails if the committed file drifts from this.
// Entries for real flagged contracts are added by hand to
// src/threat-signatures.js with `node cli.js signature <chain> <address>`.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createLocalChain } from '../test/helpers/local-chain.js';
import { buildBaseline, loadBaseline, makeEntry, entrySource } from '../src/similarity.js';

// Plain reference tokens: their code is the boilerplate every token shares
// (ERC-20; ERC-20 + Ownable + mint). FakeUSDT is NOT a seed: its code is the
// same as RenouncedToken's, only the name is fake, and the lookalike rule
// (src/known-tokens.js) already catches that.
export const BASELINE_CONTRACTS = ['CleanToken', 'RenouncedToken'];
// [contract, reason] — reasons are ThreatRegistry's code-fact codes (src/threat-reasons.js).
export const SEED_CONTRACTS = [
  ['ScamToken', 'owner-can-block-transfers'],       // blacklist, pause, trading switch, mint
  ['QuietHoneypot', 'cannot-sell-in-simulation'],   // only the owner can sell, under a harmless name
  ['NotLaunched', 'cannot-sell-in-simulation'],     // nothing can leave the pool
  ['HiddenPowers', 'owner-can-move-holder-funds'],  // mint, freeze and seize under unknown names
  ['Killable', 'owner-can-move-holder-funds'],      // SELFDESTRUCT sends the contract's funds to the deployer
];

async function runtimeCodes(names) {
  const out = [];
  for (const optimize of [true, false]) {
    const chain = await createLocalChain({ optimize });
    for (const name of names) {
      const addr = await chain.deploy(name);
      out.push({ name, optimize, code: await chain.rpc.call('eth_getCode', [addr, 'latest']) });
    }
  }
  return out;
}

/** The generated module's text. */
export async function buildThreatSignatures() {
  const stored = await buildBaseline((await runtimeCodes(BASELINE_CONTRACTS)).map((c) => c.code));
  const baseline = loadBaseline(stored);
  const reasons = Object.fromEntries(SEED_CONTRACTS);
  const seeds = [];
  for (const c of await runtimeCodes(SEED_CONTRACTS.map(([n]) => n))) {
    seeds.push(await makeEntry(c.code, baseline, {
      reason: reasons[c.name],
      source: `test/helpers/contracts.sol ${c.name} (solc 0.8.26, optimizer ${c.optimize ? 'on' : 'off'})`,
    }));
  }
  const chunk = (s) => s.match(/.{1,96}/g).map((x) => `    '${x}'`).join(' +\n');
  return `// GENERATED by scripts/build-threat-signatures.js (npm run threat-signatures). Do not edit.
// Baseline: ${BASELINE_CONTRACTS.join(', ')} (boilerplate removed before comparing).
// Seeds: ${SEED_CONTRACTS.map(([n]) => n).join(', ')}.

export const BASELINE = {
  id: '${stored.id}',
  selectors: ${JSON.stringify(stored.selectors).replace(/"/g, "'").replace(/,/g, ', ')},
  shingles:
${chunk(stored.shingles)},
};

export const SEEDS = [
${seeds.map((e) => entrySource(e)).join('\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../src/threat-signatures.generated.js', import.meta.url), await buildThreatSignatures());
  console.log(`wrote ${SEED_CONTRACTS.length * 2} seed entries`);
}
