// Regenerates the similarity baseline (src/threat-signatures.generated.js) and
// the TEST-ONLY reference samples (test/fixtures/reference-samples.generated.js).
//
// Baseline: the honest tokens in scripts/baseline-tokens.sol (minimal ERC-20s
// and OpenZeppelin-style ERC-20 + Pausable / Permit / Burnable / Capped /
// Ownable / Ownable2Step / AccessControl / plain blacklist), deployed on the
// in-memory EVM (solc 0.8.26, optimizer on and off) and read back exactly as a
// runner reads a chain. Nothing is downloaded or paid for.
//
// Reference samples: test contracts (test/helpers/contracts.sol) with known-bad
// patterns. They are fixtures for the tests ONLY: no runner ever flagged them,
// so they never ship in Neuro's dataset (src/threat-signatures.js, which
// starts empty). They carry no on-chain flag reference (flag: null).
//
//   npm run threat-signatures
//
// test/similarity.test.js fails if the committed files drift from this.
// Entries for real flagged contracts are added by hand to
// src/threat-signatures.js with `node cli.js signature <chain> <address>
// --flag-key 0x… --report-hash 0x…`.

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createLocalChain } from '../test/helpers/local-chain.js';
import { buildBaseline, loadBaseline, makeEntry, entrySource } from '../src/similarity.js';

// Honest code every token may share (scripts/baseline-tokens.sol), one pattern each.
export const BASELINE_CONTRACTS = [
  'MinToken', 'MinOwnedMintToken',
  'OZToken', 'OZOwnableMintToken', 'OZPausableToken', 'OZPermitToken', 'OZBurnableToken', 'OZCappedToken',
  'OZOwnable2StepToken', 'OZAccessControlToken', 'OZBlacklistToken',
];
// [contract, reason] — test fixtures; reasons are ThreatRegistry code-fact codes (src/threat-reasons.js).
// FakeUSDT is NOT one: its code is an ordinary mintable token, only the name is
// fake, and the lookalike rule (src/known-tokens.js) already catches that.
export const SAMPLE_CONTRACTS = [
  ['ScamToken', 'owner-can-block-transfers'],       // blacklist, pause, trading switch, mint
  ['QuietHoneypot', 'cannot-sell-in-simulation'],   // only the owner can sell, under a harmless name
  ['NotLaunched', 'cannot-sell-in-simulation'],     // nothing can leave the pool
  ['HiddenPowers', 'owner-can-move-holder-funds'],  // mint, freeze and seize under unknown names
  ['Killable', 'owner-can-move-holder-funds'],      // SELFDESTRUCT sends the contract's funds to the deployer
];

async function runtimeCodes(names) {
  const out = [];
  for (const optimize of [true, false]) {
    const chain = await createLocalChain({ optimize });
    for (const name of names) {
      const addr = await chain.deploy(name);
      out.push({ name, optimize, code: await chain.rpc.call('eth_getCode', [addr, 'latest']) });
    }
  }
  return out;
}

const chunk = (s) => s.match(/.{1,96}/g).map((x) => `    '${x}'`).join(' +\n');

/** {baseline: text of src/threat-signatures.generated.js, samples: text of the test fixture}. */
export async function buildThreatSignatures() {
  const stored = await buildBaseline((await runtimeCodes(BASELINE_CONTRACTS)).map((c) => c.code));
  const baseline = loadBaseline(stored);
  const reasons = Object.fromEntries(SAMPLE_CONTRACTS);
  const samples = [];
  for (const c of await runtimeCodes(SAMPLE_CONTRACTS.map(([n]) => n))) {
    samples.push(await makeEntry(c.code, baseline, {
      reason: reasons[c.name],
      source: `test/helpers/contracts.sol ${c.name} (solc 0.8.26, optimizer ${c.optimize ? 'on' : 'off'})`,
    }));
  }
  return {
    baseline: `// GENERATED by scripts/build-threat-signatures.js (npm run threat-signatures). Do not edit.
// Similarity baseline: honest code removed before comparing (scripts/baseline-tokens.sol:
// ${BASELINE_CONTRACTS.join(', ')}; solc 0.8.26, optimizer on and off).

export const BASELINE = {
  id: '${stored.id}',
  selectors: ${JSON.stringify(stored.selectors).replace(/"/g, "'").replace(/,/g, ', ')},
  shingles:
${chunk(stored.shingles)},
};
`,
    samples: `// GENERATED by scripts/build-threat-signatures.js (npm run threat-signatures). Do not edit.
// TEST FIXTURES ONLY: reference samples built from test contracts
// (${SAMPLE_CONTRACTS.map(([n]) => n).join(', ')}). No runner flagged them;
// they never ship in Neuro's dataset (src/threat-signatures.js).

export const REFERENCE_SAMPLES = [
${samples.map((e) => entrySource(e)).join('\n')}
];
`,
  };
}

export const BASELINE_FILE = new URL('../src/threat-signatures.generated.js', import.meta.url);
export const SAMPLES_FILE = new URL('../test/fixtures/reference-samples.generated.js', import.meta.url);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { baseline, samples } = await buildThreatSignatures();
  writeFileSync(BASELINE_FILE, baseline);
  mkdirSync(new URL('./', SAMPLES_FILE), { recursive: true });
  writeFileSync(SAMPLES_FILE, samples);
  console.log(`wrote the baseline (${BASELINE_CONTRACTS.length} contracts x 2) and ${SAMPLE_CONTRACTS.length * 2} test reference samples`);
}
