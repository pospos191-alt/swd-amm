#!/usr/bin/env node
// Writes the circom circuit for "this feature vector yields this margin under
// model hash H" from the packed model NeuroScore runs (ml/onchain/model.fixed.json).
//
//   node ml/onchain/zk/gen-circuit.js [--model ml/onchain/model.fixed.json] [--out ml/onchain/zk/out/neuro_score.circom]
//
// Statement (Groth16, BN254):
//   private  x[nFeatures]  the integer features (u32 each, as NeuroScore takes them)
//   private  salt          hides the vector inside the commitment
//   public   commitment    Poseidon chain over [salt, x packed 7 per field element]
//   public   margin        Z + 2^40, Z = the model's integer margin (ml/onchain/fixed.js evalFixed)
//   public   hashHi, hashLo  the two 128-bit halves of H = keccak256(model bytes): constants of the circuit
// The model (thresholds, leaves, base) is hard-wired: the circuit IS the model H, and
// exposing H lets a contract check the proof is for the model it has active. The
// calibrated score is trunc(calibA * Z / scale) + calibB, cheap to compute from Z.
//
// Size: one 33-bit decomposition per distinct (feature, threshold) pair (x <= T is
// bit 32 of T + 2^32 - x), one multiplication per internal node (the path
// indicators), a 32-bit range check per feature, two Poseidon hashes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fromHex, header, HEADER, NODE_BYTES, LEAF } from '../fixed.js';

export const MARGIN_OFFSET = 2n ** 40n;
export const PACK = 7; // u32 features per field element (224 bits < 254)

/** circom source for packed model bytes (Uint8Array) with model hash `hash` (0x hex). */
export function circuitSource(bytes, hash) {
  const h = header(bytes);
  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const cmpIndex = new Map(); // "f:T" -> k
  const cmps = [];
  const muls = []; // constraint lines for path indicators
  const leafTerms = [];
  let o = HEADER + h.nTrees;
  let sig = 0;
  for (let t = 0; t < h.nTrees; t++) {
    const n = bytes[HEADER + t];
    const walk = (i, ind) => {
      const p = o + i * NODE_BYTES;
      const f = bytes[p];
      if (f === LEAF) {
        const v = dv.getInt32(p + 1);
        if (v !== 0) leafTerms.push(ind === '1' ? `${v}` : `${v} * (${ind})`);
        return;
      }
      const T = dv.getUint32(p + 1);
      const key = `${f}:${T}`;
      if (!cmpIndex.has(key)) { cmpIndex.set(key, cmps.length); cmps.push({ f, T }); }
      const c = `c[${cmpIndex.get(key)}]`;
      let left;
      if (ind === '1') left = c;
      else { left = `p[${sig}]`; muls.push(`    p[${sig}] <== (${ind}) * ${c};`); sig++; }
      walk(i + 1, left);
      walk(bytes[p + 5], ind === '1' ? `1 - ${c}` : `${ind} - ${left}`);
    };
    walk(0, '1');
    o += n * NODE_BYTES;
  }
  const nf = h.nFeatures;
  const groups = Math.ceil(nf / PACK);
  const H = BigInt(hash);
  const hi = H >> 128n;
  const lo = H & ((1n << 128n) - 1n);
  const packLines = [];
  for (let g = 0; g < groups; g++) {
    const terms = [];
    for (let j = 0; j < PACK && g * PACK + j < nf; j++) terms.push(j === 0 ? `x[${g * PACK}]` : `x[${g * PACK + j}] * ${1n << BigInt(32 * j)}`);
    packLines.push(`    e[${g}] <== ${terms.join(' + ')};`);
  }
  // Poseidon chain over [salt, e...]: the first hash takes 16 inputs, each next one [h, up to 15 more].
  const items = ['salt', ...Array.from({ length: groups }, (_, g) => `e[${g}]`)];
  const hashLines = [];
  let prev = null;
  let k = 0;
  let pos = 0;
  while (pos < items.length) {
    const take = prev == null ? items.slice(pos, pos + 16) : [prev, ...items.slice(pos, pos + 15)];
    pos += prev == null ? Math.min(16, items.length - pos) : Math.min(15, items.length - pos);
    hashLines.push(`    component h${k} = Poseidon(${take.length});`);
    take.forEach((it, j) => hashLines.push(`    h${k}.inputs[${j}] <== ${it};`));
    prev = `h${k}.out`;
    k++;
  }
  return `pragma circom 2.1.6;
// GENERATED by zetaphy-neuro/ml/onchain/zk/gen-circuit.js from model hash ${hash}
// (${h.nTrees} trees, ${nf} features, ${cmps.length} distinct comparisons, ${muls.length} path products). Do not edit.

include "circomlib/circuits/bitify.circom";
include "circomlib/circuits/poseidon.circom";

template NeuroScore() {
    signal input x[${nf}];
    signal input salt;
    signal output commitment;
    signal output margin;
    signal output hashHi;
    signal output hashLo;

    // every feature is a u32 (also makes the packing below one-to-one)
    component rc[${nf}];
    for (var i = 0; i < ${nf}; i++) {
        rc[i] = Num2Bits(32);
        rc[i].in <== x[i];
    }

    // c[k] = (x[f] <= T): bit 32 of T + 2^32 - x[f]
    var F[${cmps.length}] = [${cmps.map((c) => c.f).join(', ')}];
    var T[${cmps.length}] = [${cmps.map((c) => c.T).join(', ')}];
    signal c[${cmps.length}];
    component cb[${cmps.length}];
    for (var k = 0; k < ${cmps.length}; k++) {
        cb[k] = Num2Bits(33);
        cb[k].in <== T[k] + ${2n ** 32n} - x[F[k]];
        c[k] <== cb[k].out[32];
    }

    // path indicators: exactly one leaf per tree has indicator 1
    signal p[${Math.max(1, muls.length)}];
${muls.join('\n')}
${muls.length ? '' : '    p[0] <== 0;'}
    // margin: a linear sum, accumulated line by line (one long expression overflows circom's parser)
    var acc = ${MARGIN_OFFSET + BigInt(h.base)};
${leafTerms.map((t) => `    acc += ${t};`).join('\n')}
    margin <== acc;

    signal e[${groups}];
${packLines.join('\n')}
${hashLines.join('\n')}
    commitment <== ${prev};

    hashHi <== ${hi};
    hashLo <== ${lo};
}

component main = NeuroScore();
`;
}

/** The circuit's input for integer features and a salt. */
export const circuitInput = (q, salt) => ({ x: q.map(String), salt: String(salt) });

function arg(name, def) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : def;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const modelPath = arg('model', new URL('../model.fixed.json', import.meta.url).pathname);
  const out = arg('out', new URL('./out/neuro_score.circom', import.meta.url).pathname);
  const art = JSON.parse(readFileSync(modelPath, 'utf8'));
  const src = circuitSource(fromHex(art.bytes), art.hash);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, src);
  console.log(`${out}: ${src.length} bytes`);
}
