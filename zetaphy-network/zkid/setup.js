#!/usr/bin/env node
// Private identity: build the circuit, make its DEV Groth16 key, export the verifier, the browser prover files, the
// contract-test fixture and a benchmark.
//
//   cd zetaphy-network/zkid && npm ci && node setup.js [--ptau <path to the pinned phase-1 file>]
//
//   1. circuits/identity.circom (depth 20) compiled with circom 2 (circom2 WASM build, --O2)
//   2. phase 1 = the PUBLIC Perpetual Powers of Tau file Neuro's zkML pins (zetaphy-neuro/ml/onchain/zk/ceremony/
//      phase1.json; sha256 + blake2b checked)
//   3. phase 2 = ONE contribution with random entropy made on this machine, then forgotten. DEV / TESTNET ONLY: whoever
//      ran this could have kept the entropy and could forge proofs (fake members, unlimited nullifiers). Mainnet needs
//      its own public multi-party phase-2 ceremony (the zetaphy-neuro/ml/onchain/zk/ceremony/ tooling pattern).
//   4. ../contracts/ZkIdentityVerifier.sol (snarkjs' Groth16 template, labelled DEV, with the zkey's sha256)
//   5. ../../zetaphy-hub/zkid/: identity.wasm, identity.zkey, manifest.json (sizes, sha256, verification key)
//   6. ../test/fixtures/zkid.json: proofs for the fixed scenario of lib.js (the contract test replays it)
//   7. BENCH.json: constraints, sizes, prove/verify times on this machine
import { writeFileSync, mkdirSync, copyFileSync, readFileSync, statSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import os from 'node:os';
import * as snarkjs from 'snarkjs';
import { OUT, HUB_ZKID, p, run, SNARKJS_CLI, SNARKJS_VERSION, buildCircuit, getPtau, fileHash, secs, PHASE1, PEOPLE, leavesAfter, SCOPES, RECIPIENTS, airdropSignal, pollSignal } from './lib.js';
import { proofInput, proofWords, buildTree, commitment, DEPTH } from '../../zetaphy-hub/zkid-core.js';

const arg = (name) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : undefined; };
const NET = new URL('../', import.meta.url);
const FEE = 10n ** 16n;
mkdirSync(OUT, { recursive: true });
const bench = { when: new Date().toISOString(), node: process.version, cpu: os.cpus()[0]?.model, cores: os.cpus().length, snarkjs: SNARKJS_VERSION, depth: DEPTH };

// 1. circuit
const c = buildCircuit();
bench.circuit = { constraints: c.constraints, compileSeconds: secs(c.ms) };
console.log(`circuit: ${c.constraints} constraints`);

// 2. phase 1 (public, pinned)
const ptau = await getPtau(arg('ptau'));
bench.phase1 = { name: PHASE1.name, sha256: PHASE1.sha256 };

// 3. phase 2: DEV, one party
const r1cs = p(new URL('identity.r1cs', OUT));
const z0 = p(new URL('identity_0000.zkey', OUT));
const zkey = p(new URL('identity_dev.zkey', OUT));
let t = performance.now();
run(SNARKJS_CLI, ['groth16', 'setup', r1cs, ptau, z0]);
run(SNARKJS_CLI, ['zkey', 'contribute', z0, zkey, '--name=ZETAPHY zkid DEV single-party (testnet only)', `-e=${randomBytes(64).toString('hex')}`]);
run(SNARKJS_CLI, ['zkey', 'verify', r1cs, ptau, zkey]);
bench.setupSeconds = secs(performance.now() - t);
const vkey = await snarkjs.zKey.exportVerificationKey(zkey);
const zkeySha = await fileHash(zkey);

// 4. verifier
const template = readFileSync(new URL('snarkjs/templates/verifier_groth16.sol.ejs', new URL('./node_modules/', import.meta.url)), 'utf8');
let sol = await snarkjs.zKey.exportSolidityVerifier(zkey, { groth16: template });
sol = sol.replace(/contract Groth16Verifier/, 'contract ZkIdentityVerifier').replace(/pragma solidity [^;]+;/, 'pragma solidity 0.8.26;');
const binding = `
    /// sha256 of the zkey this verifier was exported from (zetaphy-hub/zkid/identity.zkey, its manifest.json)
    bytes32 public constant ZKEY_SHA256 = 0x${zkeySha};
    /// true: a single-party DEV setup (testnet only). A public multi-party ceremony must replace it before mainnet.
    bool public constant DEV_SETUP = true;
`;
const end = sol.lastIndexOf('}');
sol = sol.slice(0, end) + binding + sol.slice(end);
sol = `// GENERATED by zetaphy-network/zkid/setup.js (snarkjs ${SNARKJS_VERSION} Groth16 template) for circuits/identity.circom (depth ${DEPTH}).\n`
  + `// DEV setup: phase 1 = Perpetual Powers of Tau 0080 (public); phase 2 = ONE contribution by ONE machine. Testnet only:\n`
  + `// whoever ran it could forge proofs. Mainnet needs a public multi-party phase-2 ceremony (docs/future/zk-identity.md).\n` + sol;
writeFileSync(new URL('contracts/ZkIdentityVerifier.sol', NET), sol);

// 5. browser prover files
mkdirSync(HUB_ZKID, { recursive: true });
const wasm = p(new URL('identity_js/identity.wasm', OUT));
copyFileSync(wasm, p(new URL('identity.wasm', HUB_ZKID)));
copyFileSync(zkey, p(new URL('identity.zkey', HUB_ZKID)));
const manifest = {
  about: 'ZETAPHY private identity prover files (zetaphy-network/zkid/setup.js). DEV single-party phase 2: testnet only.',
  circuit: 'zetaphy-network/zkid/circuits/identity.circom', depth: DEPTH, constraints: c.constraints, publicSignals: ['root', 'nullifier', 'scope', 'signalHash', 'minLevel'],
  setup: { phase1: PHASE1.name, phase2: 'DEV: one contribution, one machine (testnet only)' },
  wasm: { file: 'identity.wasm', bytes: statSync(wasm).size, sha256: await fileHash(wasm) },
  zkey: { file: 'identity.zkey', bytes: statSync(zkey).size, sha256: zkeySha },
  vkey,
};
writeFileSync(new URL('manifest.json', HUB_ZKID), JSON.stringify(manifest, null, 1) + '\n');
bench.files = { wasmBytes: manifest.wasm.bytes, zkeyBytes: manifest.zkey.bytes };

// 6. fixture
const leaves2 = leavesAfter(2);
const leaves3 = leavesAfter(3);
const root2 = buildTree(leaves2).root;
const root3 = buildTree(leaves3).root;
const jobs = {
  claim: ['alice', leaves3, SCOPES.airdrop, airdropSignal(RECIPIENTS.r1, 0n), 1],
  claimAgain: ['alice', leaves3, SCOPES.airdrop, airdropSignal(RECIPIENTS.r4, 0n), 1],
  relayed: ['bob', leaves3, SCOPES.airdrop, airdropSignal(RECIPIENTS.r2, FEE), 1],
  oldRootFresh: ['alice', leaves2, SCOPES.oldRoot, airdropSignal(RECIPIENTS.r3, 0n), 1],
  oldRootStale: ['bob', leaves2, SCOPES.oldRoot, airdropSignal(RECIPIENTS.r2, 0n), 1],
  unique: ['bob', leaves3, SCOPES.unique, airdropSignal(RECIPIENTS.r2, 0n), 2],
  carolUnique: ['carol', leaves3, SCOPES.unique, airdropSignal(RECIPIENTS.r3, 0n), 1], // valid proof, minLevel 1 < the airdrop's 2
  vote: ['alice', leaves3, SCOPES.poll, pollSignal(SCOPES.poll, 1n), 1],
  vote2: ['bob', leaves3, SCOPES.poll, pollSignal(SCOPES.poll, 0n), 1],
  voteAgain: ['alice', leaves3, SCOPES.poll, pollSignal(SCOPES.poll, 0n), 1],
};
const proofs = {};
const proveTimes = [];
for (const [name, [who, leaves, scope, signalHash, minLevel]] of Object.entries(jobs)) {
  const { input } = proofInput({ id: PEOPLE[who].id, leaves, scope, signalHash, minLevel });
  t = performance.now();
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, wasm, zkey, undefined, undefined, { singleThread: true });
  proveTimes.push(performance.now() - t);
  if (!(await snarkjs.groth16.verify(vkey, publicSignals, proof))) throw new Error(`${name}: proof does not verify`);
  proofs[name] = { who, words: proofWords(proof).map(String), pub: publicSignals };
  console.log(`proof ${name}: ${secs(proveTimes.at(-1))} s`);
}
const fixture = {
  about: 'zetaphy-network/zkid/setup.js: Groth16 proofs for the fixed scenario of zkid/lib.js (test identities from public constants). Public signals: root, nullifier, scope, signalHash, minLevel.',
  zkeySha256: zkeySha, root2: String(root2), root3: String(root3), fee: String(FEE),
  scopes: Object.fromEntries(Object.entries(SCOPES).map(([k, v]) => [k, String(v)])), recipients: RECIPIENTS,
  people: Object.fromEntries(Object.entries(PEOPLE).map(([k, v]) => [k, { commitment: String(commitment(v.id)), level: v.level }])),
  proofs,
};
writeFileSync(new URL('test/fixtures/zkid.json', NET), JSON.stringify(fixture, null, 1) + '\n');

// 7. benchmark
const sorted = proveTimes.slice().sort((a, b) => a - b);
bench.proveSingleThreadSeconds = { median: secs(sorted[sorted.length >> 1]), min: secs(sorted[0]), max: secs(sorted.at(-1)), n: sorted.length };
{
  const { input } = proofInput({ id: PEOPLE.alice.id, leaves: leaves3, scope: SCOPES.airdrop, signalHash: 1n, minLevel: 1 });
  t = performance.now();
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, wasm, zkey);
  bench.proveMultiThreadSeconds = secs(performance.now() - t);
  t = performance.now();
  for (let i = 0; i < 5; i++) await snarkjs.groth16.verify(vkey, publicSignals, proof);
  bench.verifyJsSeconds = secs((performance.now() - t) / 5);
}
bench.proofBytes = { groth16: 8 * 32, calldataWithPublicSignals: (8 + 5) * 32 };
writeFileSync(new URL('BENCH.json', import.meta.url), JSON.stringify(bench, null, 1) + '\n');
console.log(JSON.stringify(bench, null, 1));
process.exit(0);
