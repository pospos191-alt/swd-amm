#!/usr/bin/env node
// Writes the two non-circuit copies of Poseidon(2) (BN254, t = 3, 8 full + 57 partial rounds) from circomlib's own
// constants (node_modules/circomlib/circuits/poseidon_constants.circom, circomlib 2.0.5), so the circuit, the browser
// and the chain hash the same way:
//   zetaphy-hub/zkid-poseidon.js            BigInt Poseidon(2) for the browser and Node (no dependencies)
//   zetaphy-network/contracts/PoseidonT3.sol  the same function in EVM assembly (the identity tree's hash on chain)
// Both use circomlib's optimized form (sparse partial-round matrices S, pre-matrix P), exactly as poseidon.circom.
// test/circuit.test.js checks the JS against the compiled circuit; zetaphy-network/test/zkid.test.js checks the
// contract against the JS.
//   node gen-poseidon.js            write both files
//   node gen-poseidon.js --check    exit 1 if a committed file differs from what this writes
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = new URL('./node_modules/circomlib/circuits/poseidon_constants.circom', import.meta.url);
const HUB = new URL('../../zetaphy-hub/zkid-poseidon.js', import.meta.url);
const SOL = new URL('../contracts/PoseidonT3.sol', import.meta.url);
const CIRCOMLIB = JSON.parse(readFileSync(new URL('./node_modules/circomlib/package.json', import.meta.url), 'utf8')).version;

/** circomlib's constants for t = 3 (two inputs). */
export function constantsT3() {
  const src = readFileSync(SRC, 'utf8');
  const block = (fn) => {
    const start = src.indexOf(`function ${fn}(t)`);
    const end = src.indexOf('function ', start + 10);
    const body = src.slice(start, end === -1 ? undefined : end);
    return body.slice(body.indexOf('} else if (t==3) {'), body.indexOf('} else if (t==4) {')).match(/0x[0-9a-fA-F]+/g).map((h) => BigInt(h));
  };
  const k = { C: block('POSEIDON_C'), S: block('POSEIDON_S'), M: block('POSEIDON_M'), P: block('POSEIDON_P') };
  if (k.C.length !== 81 || k.S.length !== 285 || k.M.length !== 9 || k.P.length !== 9) throw new Error('unexpected circomlib constants');
  return k;
}

const hx = (n) => '0x' + n.toString(16).padStart(64, '0');

function jsModule(k) {
  const arr = (a, per = 3) => a.map((n, i) => `'${n.toString(16)}'${(i + 1) % per === 0 ? ',\n' : ', '}`).join('').replace(/, $/, '\n');
  return `// GENERATED by zetaphy-network/zkid/gen-poseidon.js from circomlib ${CIRCOMLIB} (circuits/poseidon_constants.circom, t = 3).
// Do not edit: rerun the generator. Poseidon(2) over the BN254 scalar field, circomlib's optimized form, BigInt only.
// The identity circuit, this file and contracts/PoseidonT3.sol compute the same function (checked in the tests).

export const F = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const h = (a) => a.map((x) => BigInt('0x' + x));
const C = h([
${arr(k.C)}]);
const S = h([
${arr(k.S, 5)}]);
const M = h([${k.M.map((n) => `'${n.toString(16)}'`).join(', ')}]);
const P = h([${k.P.map((n) => `'${n.toString(16)}'`).join(', ')}]);

const p5 = (x) => { const s = (x * x) % F; return (((s * s) % F) * x) % F; };
const mix = (m, s) => [0, 1, 2].map((i) => (m[i] * s[0] + m[3 + i] * s[1] + m[6 + i] * s[2]) % F);

/** Poseidon(a, b) as circomlib's Poseidon(2) template; a and b must be field elements (0 <= x < F). */
export function poseidon2(a, b) {
  a = BigInt(a); b = BigInt(b);
  if (a < 0n || a >= F || b < 0n || b >= F) throw new RangeError('poseidon2: input is not a field element');
  let s = [C[0], (a + C[1]) % F, (b + C[2]) % F];
  for (let r = 0; r < 3; r++) s = mix(M, s.map((x, i) => (p5(x) + C[(r + 1) * 3 + i]) % F));
  s = mix(P, s.map((x, i) => (p5(x) + C[12 + i]) % F));
  for (let r = 0; r < 57; r++) {
    const x0 = (p5(s[0]) + C[15 + r]) % F;
    const o = 5 * r;
    s = [(S[o] * x0 + S[o + 1] * s[1] + S[o + 2] * s[2]) % F, (s[1] + x0 * S[o + 3]) % F, (s[2] + x0 * S[o + 4]) % F];
  }
  for (let r = 0; r < 3; r++) s = mix(M, s.map((x, i) => (p5(x) + C[72 + r * 3 + i]) % F));
  s = s.map(p5);
  return (M[0] * s[0] + M[3] * s[1] + M[6] * s[2]) % F;
}
`;
}

function solidity(k) {
  const L = [];
  const add = (x, c) => `addmod(${x}, ${hx(c)}, F)`;
  const mixLines = (m, pre = '') => {
    const e = (i) => `addmod(addmod(mulmod(s0, ${hx(m[i])}, F), mulmod(s1, ${hx(m[3 + i])}, F), F), mulmod(s2, ${hx(m[6 + i])}, F), F)`;
    L.push(`            ${pre}{ let n0 := ${e(0)} let n1 := ${e(1)} s2 := ${e(2)} s0 := n0 s1 := n1 }`);
  };
  const full = (off) => {
    L.push(`            s0 := ${add('p5(s0)', k.C[off])} s1 := ${add('p5(s1)', k.C[off + 1])} s2 := ${add('p5(s2)', k.C[off + 2])}`);
  };
  L.push(`            let s0 := ${hx(k.C[0])}`, `            let s1 := ${add('a', k.C[1])}`, `            let s2 := ${add('b', k.C[2])}`);
  for (let r = 0; r < 3; r++) { full((r + 1) * 3); mixLines(k.M); }
  full(12); mixLines(k.P);
  for (let r = 0; r < 57; r++) {
    const o = 5 * r;
    L.push(`            s0 := ${add('p5(s0)', k.C[15 + r])} { let n0 := addmod(addmod(mulmod(s0, ${hx(k.S[o])}, F), mulmod(s1, ${hx(k.S[o + 1])}, F), F), mulmod(s2, ${hx(k.S[o + 2])}, F), F) s1 := addmod(s1, mulmod(s0, ${hx(k.S[o + 3])}, F), F) s2 := addmod(s2, mulmod(s0, ${hx(k.S[o + 4])}, F), F) s0 := n0 }`);
  }
  for (let r = 0; r < 3; r++) { full(72 + r * 3); mixLines(k.M); }
  L.push(`            s0 := p5(s0) s1 := p5(s1) s2 := p5(s2)`);
  L.push(`            out := addmod(addmod(mulmod(s0, ${hx(k.M[0])}, F), mulmod(s1, ${hx(k.M[3])}, F), F), mulmod(s2, ${hx(k.M[6])}, F), F)`);
  return `// GENERATED by zetaphy-network/zkid/gen-poseidon.js from circomlib ${CIRCOMLIB} (circuits/poseidon_constants.circom, t = 3).
// Do not edit: rerun the generator.
// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

/// @title PoseidonT3: Poseidon(a, b) over the BN254 scalar field, as circomlib's Poseidon(2) template
/// @notice The hash of ZkIdentityRegistry's Merkle tree, so the tree on chain and the identity circuit agree.
///   circomlib's optimized form (8 full rounds, 57 partial rounds with sparse matrices), straight-line EVM assembly.
///   Reverts on inputs that are not field elements. Same function as zetaphy-hub/zkid-poseidon.js.
contract PoseidonT3 {
    uint256 internal constant F = 21888242871839275222246405745257275088548364400416034343698204186575808495617;

    function poseidon(uint256[2] calldata x) external pure returns (uint256 out) {
        uint256 a = x[0];
        uint256 b = x[1];
        require(a < F && b < F, "PoseidonT3: not a field element");
        assembly {
            function p5(v) -> y {
                let s := mulmod(v, v, 0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001)
                y := mulmod(mulmod(s, s, 0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001), v, 0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001)
            }
${L.join('\n')}
        }
    }
}
`;
}

const k = constantsT3();
const files = [[HUB, jsModule(k)], [SOL, solidity(k)]];
if (process.argv.includes('--check')) {
  let bad = 0;
  for (const [u, s] of files) { let cur = ''; try { cur = readFileSync(u, 'utf8'); } catch {} if (cur !== s) { console.error(`differs: ${u.pathname}`); bad++; } }
  process.exit(bad ? 1 : 0);
} else {
  for (const [u, s] of files) { writeFileSync(u, s); console.log(`wrote ${u.pathname}`); }
}
