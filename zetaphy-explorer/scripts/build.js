// npm run build: bundles scripts/entry.js into vendor/zetaphy-lib.js (committed,
// so Vercel serves it with no build step). Every @noble import resolves from
// this folder's node_modules, so the output depends only on package-lock.json.
// Then writes src/known-abi.js (scripts/known-abi.js): the repo's contract signatures.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { buildLabels, buildCrossChain, crossChainOrigins, cspWithOrigins, parseAddressesYaml, labelsJson } from './known.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

const ownDeps = {
  name: 'own-deps',
  setup(b) {
    b.onResolve({ filter: /^@noble\// }, (args) => (args.importer.startsWith(ROOT)
      ? undefined
      : b.resolve(args.path, { kind: args.kind, resolveDir: ROOT, importer: ROOT + 'scripts/entry.js' })));
  },
};

await build({
  entryPoints: [ROOT + 'scripts/entry.js'],
  outfile: ROOT + 'vendor/zetaphy-lib.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  minify: false,
  plugins: [ownDeps],
  banner: { js: '// Generated by `npm run build` in zetaphy-explorer/ from zetaphy-network/src/{pqcert,pqtx,vaccine}.js\n// and @noble/post-quantum + @noble/hashes (MIT). Do not edit by hand.' },
});
console.log('vendor/zetaphy-lib.js written');

// src/known-abi.js: this repo's contracts as a compact signature table (uses the bundle above).
await import('./known-abi.js');
// labels.json and crosschain.json (scripts/known.js): known addresses and the Hyperlane chain table.
const REPO = fileURLToPath(new URL('../..', import.meta.url));
const readRepo = (p) => {
  if (!existsSync(REPO + p)) return null;
  const text = readFileSync(REPO + p, 'utf8');
  return p.endsWith('.yaml') ? parseAddressesYaml(text) : JSON.parse(text);
};
const json = (o) => JSON.stringify(o, null, 1) + '\n';
const labels = buildLabels(readRepo);
writeFileSync(ROOT + 'labels.json', labelsJson(labels));
const cc = buildCrossChain(readRepo);
writeFileSync(ROOT + 'crosschain.json', json(cc));
console.log(`labels.json (${Object.keys(labels.labels).length} addresses) and crosschain.json (${Object.keys(cc.chains).length} chains) written`);
// The CSP must let the browser reach the destination chains' RPCs (no change while connect-src allows https:).
const vercel = JSON.parse(readFileSync(ROOT + 'vercel.json', 'utf8'));
const cspHeader = vercel.headers[0].headers.find((x) => x.key === 'Content-Security-Policy');
const next = cspWithOrigins(cspHeader.value, crossChainOrigins(cc));
if (next !== cspHeader.value) { cspHeader.value = next; writeFileSync(ROOT + 'vercel.json', JSON.stringify(vercel, null, 2) + '\n'); console.log('vercel.json: connect-src extended'); }
// The Tools page's secp256k1 (sender recovery, personal_sign): its own file, loaded on that page only.
await build({
  entryPoints: [ROOT + 'scripts/entry-tools.js'],
  outfile: ROOT + 'vendor/zetaphy-tools-lib.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  minify: false,
  plugins: [ownDeps],
  banner: { js: '// Generated by `npm run build` in zetaphy-explorer/ from @noble/curves (secp256k1, MIT). Do not edit by hand.' },
});
console.log('vendor/zetaphy-tools-lib.js written');
// The STARK light-client page's verifier (lightclient.html): its own file, loaded on that page only.
await build({
  entryPoints: [ROOT + 'scripts/entry-starklc.js'],
  outfile: ROOT + 'vendor/starklc-lib.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  minify: true,
  plugins: [ownDeps],
  banner: { js: '// Generated by `npm run build` in zetaphy-explorer/ from zetaphy-network/src/starklc (verifier only)\n// and @noble/post-quantum + @noble/hashes (MIT). Do not edit by hand.' },
});
console.log('vendor/starklc-lib.js written');
