#!/usr/bin/env node
// Compiles tools/PresignProbe.sol (solc 0.8.26, zetaphy-network's pinned compiler) into presign-probe.js: the
// runtime code presign.js puts at the user's address inside one eth_call. Committed, so the hub needs no compiler.
//   node tools/build-presign.mjs          write presign-probe.js
//   node tools/build-presign.mjs --check  exit 1 if it differs from a fresh compile
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(new URL('../../zetaphy-network/package.json', import.meta.url));
const OUT = new URL('../presign-probe.js', import.meta.url);

export function compileProbe() {
  const solc = require('solc');
  const input = { language: 'Solidity', sources: { 'PresignProbe.sol': { content: readFileSync(new URL('./PresignProbe.sol', import.meta.url), 'utf8') } },
    settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', metadata: { appendCBOR: false }, outputSelection: { '*': { '*': ['evm.deployedBytecode.object'] } } } };
  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
  const code = '0x' + out.contracts['PresignProbe.sol'].PresignProbe.evm.deployedBytecode.object;
  return `// GENERATED by tools/build-presign.mjs from tools/PresignProbe.sol. Do not edit.\n// solc ${solc.version().replace(/\.Emscripten.*$/, '')}, optimizer 200 runs, evmVersion paris, no metadata.\n`
    + `export const PROBE_SELECTOR = '0x${keccakSel('probe(address,uint256,bytes,address[])')}';\nexport const PROBE_RUNTIME = '${code}';\n`;
}

function keccakSel(sig) {
  const { keccak256, toUtf8Bytes } = require('ethers');
  return keccak256(toUtf8Bytes(sig)).slice(2, 10);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = compileProbe();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== src) { console.error('presign-probe.js differs: run node tools/build-presign.mjs'); process.exit(1); }
  } else { writeFileSync(OUT, src); console.log('wrote presign-probe.js'); }
}
