#!/usr/bin/env node
// node tools/vendor-zkverify.mjs: bundles the pure-JavaScript BN254 pairing (@noble/curves bn254, MIT, audited) and
// keccak-256 (@noble/hashes, MIT) that zkverdict-core.js uses to check a proven Neuro verdict's Groth16 proof in the
// browser. Pure JS, no WebAssembly: the pages keep their CSP (script-src 'self', no 'wasm-unsafe-eval', no worker).
// Taken from zetaphy-network's npm install (`npm ci` there checks the tarballs against its package-lock.json), the
// same @noble/curves the network tests verify proofs with. Writes vendor/zkverify.js and vendor/zkverify.json
// (versions, tarball integrity, sha256 of the file); test/zkverdict.test.mjs checks the file against that pin.
//   node tools/vendor-zkverify.mjs           write
//   node tools/vendor-zkverify.mjs --check   only compare (exit 1 when they differ)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HUB = fileURLToPath(new URL('..', import.meta.url));
const NET = fileURLToPath(new URL('../../zetaphy-network/', import.meta.url));
const CURVES = 'node_modules/@noble/curves';
const HASHES = 'node_modules/@noble/curves/node_modules/@noble/hashes';

export async function source() {
  const lock = JSON.parse(readFileSync(`${NET}package-lock.json`, 'utf8')).packages;
  const nm = `${NET}node_modules/@noble/curves/`;
  if (!existsSync(`${nm}esm/bn254.js`)) throw new Error(`run npm ci in ${NET} first`);
  for (const k of [CURVES, HASHES]) {
    const installed = JSON.parse(readFileSync(`${NET}${k}/package.json`, 'utf8')).version;
    if (installed !== lock[k].version) throw new Error(`${k}: installed ${installed}, package-lock ${lock[k].version}: npm ci`);
  }
  const { build } = await import('esbuild');
  const out = await build({
    stdin: { contents: `export { bn254 } from './${CURVES}/esm/bn254.js';\nexport { keccak_256 } from './${HASHES}/esm/sha3.js';\n`, resolveDir: NET, loader: 'js' },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, legalComments: 'inline', write: false,
    banner: { js: `// Generated by zetaphy-hub/tools/vendor-zkverify.mjs: @noble/curves ${lock[CURVES].version} (bn254) + @noble/hashes ${lock[HASHES].version} (keccak_256), MIT, Paul Miller. Do not edit by hand.` },
  });
  const bytes = Buffer.from(out.outputFiles[0].contents);
  const meta = {
    packages: [CURVES, HASHES].map((k) => ({ package: k.split('node_modules/').at(-1), version: lock[k].version, integrity: lock[k].integrity, resolved: lock[k].resolved })),
    exports: ['bn254', 'keccak_256'], license: 'MIT', sha256: createHash('sha256').update(bytes).digest('hex'),
  };
  return { bytes, meta };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { bytes, meta } = await source();
  if (process.argv.includes('--check')) {
    const same = existsSync(`${HUB}vendor/zkverify.js`) && readFileSync(`${HUB}vendor/zkverify.js`).equals(bytes);
    console.log(same ? 'vendor/zkverify.js is up to date' : 'vendor/zkverify.js differs from a fresh bundle');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(`${HUB}vendor/zkverify.js`, bytes);
  writeFileSync(`${HUB}vendor/zkverify.json`, JSON.stringify(meta, null, 2) + '\n');
  console.log(`vendor/zkverify.js: ${bytes.length} bytes, sha256 ${meta.sha256}`);
}
