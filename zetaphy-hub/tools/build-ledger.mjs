#!/usr/bin/env node
// npm run build:ledger: bundles Ledger's own WebHID transport (@ledgerhq/hw-transport-webhid,
// Apache-2.0) and the `buffer` polyfill it needs (MIT) into vendor/ledger-hid.js, committed so
// the sites serve it from their own origin (CSP script-src 'self', no CDN, no eval).
// Only the USB transport is bundled: the Ethereum app's APDUs (address, sign transaction,
// personal_sign) are in ledger.js, so @ledgerhq/hw-app-eth (axios, ethers v5, Ledger's
// metadata services: ~112 KB gzip) is not shipped. ledger.js loads this file only when the
// user clicks "Ledger (USB)". Then `npm run sync:shared` copies it to the other sites.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { writeFileSync, readFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const HERE = fileURLToPath(new URL('..', import.meta.url));
const OUT = HERE + 'vendor/ledger-hid.js';
const ver = (p) => JSON.parse(readFileSync(`${HERE}node_modules/${p}/package.json`, 'utf8')).version;

const entry = `import { Buffer } from 'buffer';
export { default as TransportWebHID } from '@ledgerhq/hw-transport-webhid';
export { Buffer };`;
const inject = HERE + 'node_modules/.ledger-buffer-shim.js';
writeFileSync(inject, "import { Buffer } from 'buffer'; export { Buffer };\n");

await build({
  stdin: { contents: entry, resolveDir: HERE, loader: 'js' },
  outfile: OUT,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'eof',
  inject: [inject],
  define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
  banner: { js: `// Generated by \`npm run build:ledger\` in zetaphy-hub/ from @ledgerhq/hw-transport-webhid ${ver('@ledgerhq/hw-transport-webhid')} (Apache-2.0)\n// and buffer ${ver('buffer')} (MIT), ieee754 (BSD-3-Clause).\n// Ledger code: Copyright Ledger SAS, Apache License 2.0 (https://www.apache.org/licenses/LICENSE-2.0). Do not edit by hand.` },
});
const code = readFileSync(OUT);
if (/\beval\(|new Function\(/.test(code.toString())) throw new Error('eval in the bundle: refused (CSP has no unsafe-eval)');
console.log(`vendor/ledger-hid.js written: ${code.length} bytes, ${gzipSync(code, { level: 9 }).length} gzip`);
