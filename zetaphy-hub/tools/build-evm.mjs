#!/usr/bin/env node
// npm run build:evm: bundles the EthereumJS EVM (@ethereumjs/evm, common, util: MPL-2.0; with
// @noble/curves, ethereum-cryptography: MIT) into vendor/evm.js for the bug-hunting Web Worker
// (work-worker.js, fuzz-core.js). Committed, so the site serves it from its own origin
// (CSP script-src 'self': no CDN, no eval, no wasm). Loaded only when someone starts a hunt.
//   - rustbn-wasm (the bn254 precompiles 0x06-0x08, WebAssembly) is replaced by a stub that
//     refuses: a fuzz target calling those precompiles fails its call, the rest works;
//   - node's `events` becomes a small EventEmitter, `buffer` the `buffer` package and `process` a
//     module-local stand-in (no globals are set).
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const HERE = fileURLToPath(new URL('..', import.meta.url));
const OUT = HERE + 'vendor/evm.js';
const ver = (p) => JSON.parse(readFileSync(`${HERE}node_modules/${p}/package.json`, 'utf8')).version;

const EVENTS = `export class EventEmitter {
  constructor() { this._events = {}; }
  on(n, f) { (this._events[n] ??= []).push(f); return this; }
  addListener(n, f) { return this.on(n, f); }
  once(n, f) { const g = (...a) => { this.off(n, g); f(...a); }; return this.on(n, g); }
  off(n, f) { this._events[n] = (this._events[n] || []).filter((x) => x !== f); return this; }
  removeListener(n, f) { return this.off(n, f); }
  removeAllListeners(n) { if (n) delete this._events[n]; else this._events = {}; return this; }
  emit(n, ...a) { const l = this._events[n]; if (!l || !l.length) return false; for (const f of [...l]) f.apply(this, a); return true; }
  listenerCount(n) { return (this._events[n] || []).length; }
  listeners(n) { return [...(this._events[n] || [])]; }
  setMaxListeners() { return this; }
}
EventEmitter.EventEmitter = EventEmitter;
export default EventEmitter;`;
const BN = `const no = () => { throw new Error('bn254 precompiles are not in the browser EVM bundle'); };
export async function initRustBN() { return { ec_add: no, ec_mul: no, ec_pairing: no }; }`;

// node's `process` (read by `debug` and `readable-stream`): a module-local stand-in, no globals touched
const inject = HERE + 'node_modules/.evm-process-shim.js';
writeFileSync(inject, "export const process = { env: {}, browser: true, version: '', versions: {}, argv: [], platform: 'browser', nextTick: (f, ...a) => queueMicrotask(() => f(...a)) };\n");

await build({
  stdin: {
    contents: `export { EVM } from '@ethereumjs/evm';
export { Common, Chain, Hardfork } from '@ethereumjs/common';
export { Address, Account, hexToBytes, bytesToHex } from '@ethereumjs/util';`,
    resolveDir: HERE, loader: 'js',
  },
  outfile: OUT,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'eof',
  inject: [inject],
  define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
  plugins: [{
    name: 'shims',
    setup(b) {
      b.onResolve({ filter: /^events$/ }, () => ({ path: 'events', namespace: 'shim' }));
      b.onResolve({ filter: /^rustbn-wasm$/ }, () => ({ path: 'rustbn', namespace: 'shim' }));
      b.onResolve({ filter: /^buffer$/ }, () => ({ path: `${HERE}node_modules/buffer/index.js` }));
      b.onLoad({ filter: /.*/, namespace: 'shim' }, (a) => ({ contents: a.path === 'events' ? EVENTS : BN, loader: 'js' }));
    },
  }],
  banner: { js: `// Generated by \`npm run build:evm\` in zetaphy-hub/ from @ethereumjs/evm ${ver('@ethereumjs/evm')}, @ethereumjs/common ${ver('@ethereumjs/common')},\n// @ethereumjs/util ${ver('@ethereumjs/util')} (MPL-2.0, https://github.com/ethereumjs/ethereumjs-monorepo) and their MIT dependencies.\n// bn254 precompiles stubbed (no wasm). Do not edit by hand.` },
});
const code = readFileSync(OUT);
if (/\beval\(|new Function\(/.test(code.toString())) throw new Error('eval in the bundle: refused (CSP has no unsafe-eval)');
if (/WebAssembly/.test(code.toString())) throw new Error('WebAssembly in the bundle: refused (CSP has no wasm-unsafe-eval)');
console.log(`vendor/evm.js written: ${code.length} bytes, ${gzipSync(code, { level: 9 }).length} gzip`);
